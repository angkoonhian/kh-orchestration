// Decision 4: assets/scripts/verify-contract-1.mjs is kh-harness's verifier,
// copied verbatim below one stamp line. This fails, never skips, when the
// sibling checkout is absent: the copy cannot be shown to be current then.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { KH_HARNESS_DIR, KIT_VERSION, siblingAbsentMessage } from './test-repo.mjs';

const COPY = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'assets', 'scripts', 'verify-contract-1.mjs');
const SIBLING = join(KH_HARNESS_DIR, 'scripts', 'lib', 'fixtures', 'contract-1', 'verify-contract-1.mjs');

test('verify-contract-1.mjs is one stamp line and then the sibling kh-harness verifier, byte for byte', () => {
  assert.ok(existsSync(SIBLING), siblingAbsentMessage(KH_HARNESS_DIR));
  const copy = readFileSync(COPY, 'utf8');
  const stamp = `// Generated by kh-orchestration ${KIT_VERSION}. Do not edit.\n`;
  assert.ok(copy.startsWith(stamp), 'the first line is the stamp');
  assert.equal(copy.slice(stamp.length), readFileSync(SIBLING, 'utf8'));
});
