// Test-only helper: builds real git repositories in temporary directories.
// Installed code must never import this file.
import { spawnSync } from 'node:child_process';
import { accessSync, chmodSync, constants, existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, realpathSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { lfSha256 } from '../../assets/scripts/verify-contract-1.mjs';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');

export const KIT_VERSION = JSON.parse(readFileSync(join(REPO_ROOT, 'package.json'), 'utf8')).version;

function khHarnessDir() {
  return process.env.KH_HARNESS_DIR || resolve(REPO_ROOT, '..', 'kh-harness');
}

export const KH_HARNESS_DIR = khHarnessDir();

export const siblingAbsentMessage = (dir) =>
  `kh-harness was not found at ${dir}. Check out kh-harness 0.3.0 or later there, or set KH_HARNESS_DIR to its directory.`;

export const spawnFailedMessage = (file) => `${file} could not be started.`;

const DROPPED = /^(GIT_AUTHOR_|GIT_COMMITTER_|GIT_CONFIG_KEY_|GIT_CONFIG_VALUE_)/;
const SCRUBBED = [
  'CLAUDECODE', 'CLAUDE_CODE_SESSION_ID', 'GIT_DIR', 'GIT_WORK_TREE', 'GIT_INDEX_FILE', 'GIT_COMMON_DIR', 'GIT_PREFIX',
  'GIT_CONFIG_COUNT', 'GIT_CONFIG_PARAMETERS', 'GIT_EDITOR', 'GIT_ASKPASS', 'GIT_TERMINAL_PROMPT',
];

function scrub(env) {
  for (const name of Object.keys(env)) {
    if (DROPPED.test(name)) delete env[name];
  }
  for (const name of SCRUBBED) delete env[name];
  return env;
}

// The environment every test command runs in: no session markers, no identity,
// no injected git configuration, and no prompt. Tests that spawn an installed
// command directly, not through repo.git, pass this as its env.
export function testEnv() {
  return { ...scrub({ ...process.env }), GIT_CONFIG_GLOBAL: '/dev/null', GIT_CONFIG_NOSYSTEM: '1', GIT_TERMINAL_PROMPT: '0' };
}

// Installed modules take the caller's git environment (a hook's GIT_DIR and
// GIT_INDEX_FILE), so a test that calls them in-process clears this process's
// copy first. Call it once at the top of such a test file.
export function isolateProcessEnv() {
  scrub(process.env);
}

function run(file, argv, cwd) {
  const result = spawnSync(file, argv, { cwd, env: testEnv(), encoding: 'utf8' });
  if (result.error) throw new Error(spawnFailedMessage(file));
  return { status: result.status, stdout: result.stdout ?? '', stderr: result.stderr ?? '' };
}

export function makeRepo({ baseBranch = 'main', files = {} } = {}) {
  const container = realpathSync(mkdtempSync(join(tmpdir(), 'ko-test-')));
  const root = join(container, 'repo');
  mkdirSync(root);
  const git = (...argv) => run('git', argv, root);
  const write = (path, text) => {
    const target = join(root, path);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, text);
  };
  const commitAll = (message) => {
    git('add', '-A');
    const result = git('commit', '-q', '--allow-empty', '-m', message);
    if (result.status !== 0) throw new Error(`git commit failed: ${result.stderr}`);
  };
  const addWorktree = (branch) => {
    const path = join(container, `worktree-${branch.replaceAll('/', '-')}`);
    const result = git('worktree', 'add', '-q', '-b', branch, path);
    if (result.status !== 0) throw new Error(`git worktree add failed: ${result.stderr}`);
    return path;
  };
  const cleanup = () => rmSync(container, { recursive: true, force: true });

  try {
    const init = git('init', '-q', '-b', baseBranch);
    if (init.status !== 0) {
      throw new Error(`git init failed: ${init.stderr}`);
    }
    git('config', '--local', 'user.name', 'Test Owner');
    git('config', '--local', 'user.email', 'owner@example.invalid');
    git('config', '--local', 'commit.gpgsign', 'false');
    for (const [path, text] of Object.entries(files)) write(path, text);
    commitAll('initial commit');
  } catch (error) {
    cleanup();
    throw error;
  }
  return { root, git, write, commitAll, addWorktree, cleanup };
}

// One run converges: a second run reports nothing left to write.
export function installKhHarness(root) {
  const dir = khHarnessDir();
  const script = join(dir, 'scripts', 'apply.mjs');
  if (!existsSync(script)) throw new Error(siblingAbsentMessage(dir));
  const result = run('node', [script, root, '--yes', '--allow-default-branch'], root);
  if (result.status !== 0) throw new Error(`kh-harness apply failed (${result.status}): ${result.stderr}`);
}

const ASSETS = join(REPO_ROOT, 'assets', 'scripts');
const STAMP = `// Generated by kh-orchestration ${KIT_VERSION}. Do not edit.\n`;
export const EXTENSION_MODULE = '.claude/kh-orchestration/scripts/extension.mjs';
const INSTALLED_SCRIPTS = '.claude/kh-orchestration/scripts';

// A script of assets/scripts as apply installs it: the stamp line of decision 2, then the
// file. verify-contract-1.mjs carries its stamp already (decision 4).
export function installedScript(name) {
  const text = readFileSync(join(ASSETS, name), 'utf8');
  return text.startsWith(STAMP) ? text : `${STAMP}${text}`;
}

function gitCommonDir(root) {
  const result = run('git', ['rev-parse', '--git-common-dir'], root);
  if (result.status !== 0) throw new Error(`git rev-parse failed: ${result.stderr}`);
  return realpathSync(resolve(root, result.stdout.replace(/\n$/, '')));
}

// A word sh reads as itself, in single quotes.
const shQuote = (text) => `'${text.replaceAll("'", "'\\''")}'`;

const REFUSED_LINE = 'echo "kh-orchestration: the commit gate did not allow this commit." >&2';

// The variables a hook passes to node (decision 18, final hook form), each only if set: what node
// and the gate's git need, the GIT_* variables git 2.56.1 exports to its hooks (seen by experiment
// for commit, commit -a, a partial commit, amend, merge, a conflicted merge concluded, a linked
// worktree, GIT_DIR and GIT_WORK_TREE from the caller, and reference-transaction), and the three
// a caller may set to name the repository git itself uses.
const HOOK_ENV = [
  'PATH', 'HOME', 'TMPDIR', 'LANG', 'LC_ALL',
  'GIT_DIR', 'GIT_WORK_TREE', 'GIT_INDEX_FILE', 'GIT_PREFIX', 'GIT_EXEC_PATH', 'GIT_EDITOR', 'GIT_AUTHOR_NAME', 'GIT_AUTHOR_EMAIL', 'GIT_AUTHOR_DATE', 'GIT_REFLOG_ACTION',
  'GIT_COMMON_DIR', 'GIT_OBJECT_DIRECTORY', 'GIT_ALTERNATE_OBJECT_DIRECTORIES',
];
const HOOK_COMMENT = [
  '# Node starts through env -i with only these variables, each passed only if set: PATH, HOME, TMPDIR,',
  '# LANG, LC_ALL; the GIT_* variables git 2.56.1 exports to its hooks (GIT_DIR, GIT_WORK_TREE,',
  '# GIT_INDEX_FILE, GIT_PREFIX, GIT_EXEC_PATH, GIT_EDITOR, GIT_AUTHOR_NAME, GIT_AUTHOR_EMAIL,',
  '# GIT_AUTHOR_DATE, GIT_REFLOG_ACTION); and GIT_COMMON_DIR, GIT_OBJECT_DIRECTORY and',
  '# GIT_ALTERNATE_OBJECT_DIRECTORIES, which name the repository git itself uses when a caller sets',
  '# them. Nothing else reaches node: no NODE_*, no LD_*, no BASH_*.',
];

// The hooks of decision 18's final form. `sh -p` imports no function and reads no ENV, SHELLOPTS
// or PS4; the common directory is the hook's own path less /hooks/<name> (hooks live only in
// <common>/hooks; a copy elsewhere finds no gate and refuses); no command is called by name: env
// and node by the absolute paths recorded at install, the token tested by a case statement. Allow
// only on the gate's exit 0 AND its token on standard output; the git process id ($PPID) is passed
// on. reference-transaction starts node only in the prepared state of a git process that has an
// in-flight record, found by a pattern (a file, a directory or a dangling link all match), so every
// other ref update runs no command at all.
function hookScript(hook, env, node) {
  const allowlist = HOOK_ENV.map((name) => `\${${name}+"${name}=$${name}"}`).join(' ');
  const gate = [
    `if out=$(${shQuote(env)} -i ${allowlist} ${shQuote(node)} "$d/kh-orchestration/bin/gate.mjs" ${hook} "$PPID"); then`,
    "  case $out in 'kh-orchestration: allowed') exit 0 ;; esac",
    'fi',
    REFUSED_LINE,
    'exit 1',
    '',
  ];
  const header = ['#!/bin/sh -p', `# kh-orchestration ${KIT_VERSION} ${hook}. Do not edit.`, ...HOOK_COMMENT];
  if (hook !== 'reference-transaction') return [...header, 'd=${0%/hooks/*}', ...gate].join('\n');
  return [
    ...header,
    '# Only the prepared state of a git process that has an in-flight record starts node; the record',
    '# is found by a pattern, so a file, a directory or a dangling link all count, and no command runs.',
    'case $1 in prepared) ;; *) exit 0 ;; esac',
    'd=${0%/hooks/*}',
    'for f in "$d/kh-orchestration/inflight-$PPID".jso[n]; do',
    "  case $f in *'.jso[n]') exit 0 ;; esac",
    'done',
    ...gate,
  ].join('\n');
}

// The absolute path of env, found through PATH as an installer finds it.
function envPath() {
  for (const dir of (process.env.PATH ?? '').split(':').filter((entry) => entry.startsWith('/'))) {
    const candidate = join(dir, 'env');
    try {
      accessSync(candidate, constants.X_OK);
      return candidate;
    } catch {
      // not here; the next directory
    }
  }
  throw new Error('env was not found on PATH.');
}

// Test-only stand-in for Task 9's installer: every script of assets/scripts, stamped, into
// <common-dir>/kh-orchestration/bin/ (and into the working tree's
// .claude/kh-orchestration/scripts/ with `inTree`), and the three git hooks into
// <common-dir>/hooks/, naming `env` (found through PATH) and `node` by absolute path.
export function installGate(root, { inTree = false, node = process.execPath } = {}) {
  const env = envPath();
  const common = gitCommonDir(root);
  const bin = join(common, 'kh-orchestration', 'bin');
  mkdirSync(bin, { recursive: true });
  if (inTree) mkdirSync(join(root, INSTALLED_SCRIPTS), { recursive: true });
  for (const name of readdirSync(ASSETS).filter((file) => file.endsWith('.mjs'))) {
    const text = installedScript(name);
    writeFileSync(join(bin, name), text);
    if (inTree) writeFileSync(join(root, INSTALLED_SCRIPTS, name), text);
  }
  mkdirSync(join(common, 'hooks'), { recursive: true });
  for (const hook of ['pre-commit', 'pre-merge-commit', 'reference-transaction']) {
    const path = join(common, 'hooks', hook);
    writeFileSync(path, hookScript(hook, env, node));
    chmodSync(path, 0o755);
  }
  return { bin };
}

// Installs the stamped extension at EXTENSION_MODULE and registers it in a kh-harness install's
// extensions file as the contract's "extensions file" section says: written whole to a temporary
// file in .claude/kh-harness/ and renamed. Returns the entry written.
export function registerExtension(root) {
  const module = join(root, EXTENSION_MODULE);
  mkdirSync(dirname(module), { recursive: true });
  writeFileSync(module, installedScript('extension.mjs'));
  const entry = { id: 'kh-orchestration', version: KIT_VERSION, module: EXTENSION_MODULE, sha256: lfSha256(readFileSync(module)), onFailure: 'block' };
  const temporary = join(root, '.claude/kh-harness/extensions.json.tmp');
  writeFileSync(temporary, `${JSON.stringify([entry], null, 2)}\n`);
  renameSync(temporary, join(root, '.claude/kh-harness/extensions.json'));
  return entry;
}
