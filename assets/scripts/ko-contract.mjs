// Whether kh-harness contract 1 holds in a working directory for this plugin's
// extension, by the verifier copied from kh-harness (decision 4). The gate
// relies on the extension only when `checkContract1` finds no problem and no
// warning and `probeContract1` finds no problem (CONTRACT.md, "What a plugin
// must check before relying on contract 1"). No installed kh-harness script
// is imported: the verifier reads and hashes them, and runs the entry script
// in its own process.
import { closeSync, fstatSync, openSync, readSync } from 'node:fs';
import { join } from 'node:path';
import { checkContract1, lfSha256, probeContract1 } from './verify-contract-1.mjs';

export const EXTENSION_ID = 'kh-orchestration';
export const MODULE = '.claude/kh-orchestration/scripts/extension.mjs';
// kh-harness refuses a module over 1 MiB, so nothing larger is read.
const MAX_MODULE_BYTES = 1024 * 1024;
// Decision 2's stamp line. The version is the extension's own: apply (Task 9) writes the entry
// with the version it stamps, so reading it here makes the entry a function of the installed
// file alone, whichever kit's gate is in bin/.
export const STAMP = /^\/\/ Generated by kh-orchestration ([^\s]+)\. Do not edit\.\r?\n/;

export const extensionUnreadableMessage = `${MODULE} is missing, not a regular file, or larger than 1 MiB.`;
export const noStampMessage = `${MODULE} does not begin with the line "// Generated by kh-orchestration <version>. Do not edit."`;
const unexpectedMessage = 'the contract 1 check failed unexpectedly';

class ContractError extends Error {}

// A hook input as Claude Code sends one before a tool call (CONTRACT.md, "How each extension is
// run"), of a call the extension always blocks. `cwd` is the repository, added by contractHolds.
export const PROBE_PAYLOAD = Object.freeze({
  session_id: 'kh-orchestration-probe',
  hook_event_name: 'PreToolUse',
  tool_name: 'Bash',
  tool_input: Object.freeze({ command: 'git commit --no-verify -m probe' }),
  tool_use_id: 'kh-orchestration-probe',
});

function readModule(root) {
  let fd;
  try {
    fd = openSync(join(root, MODULE), 'r');
    const stat = fstatSync(fd);
    if (!stat.isFile() || stat.size > MAX_MODULE_BYTES) throw new ContractError(extensionUnreadableMessage);
    const bytes = Buffer.alloc(stat.size);
    let read = 0;
    while (read < bytes.length) {
      const count = readSync(fd, bytes, read, bytes.length - read, read);
      if (count === 0) break;
      read += count;
    }
    return bytes.subarray(0, read);
  } catch (error) {
    if (error instanceof ContractError) throw error;
    throw new ContractError(extensionUnreadableMessage);
  } finally {
    if (fd !== undefined) closeSync(fd);
  }
}

/**
 * The entry this plugin writes for its extension, built from the extension
 * installed in `root`'s working directory: its path, the version of its stamp
 * line, its hash by the contract's hashing rule, and `onFailure: "block"`, the
 * only value under which a gate holds. Throws fixed text when the module
 * cannot be read or carries no stamp line.
 */
export const ownEntry = (root) => entryOf(readModule(root));

/**
 * The entry for an extension module of `bytes`: the version of its stamp line, its hash by the
 * contract's rule, `onFailure: "block"`. Throws fixed text when it carries no stamp line. The
 * installer builds the entry it writes from the plugin's shipped module with it.
 */
export function entryOf(bytes) {
  const stamp = bytes.toString('utf8').match(STAMP);
  if (stamp === null) throw new ContractError(noStampMessage);
  return { id: EXTENSION_ID, version: stamp[1], module: MODULE, sha256: lfSha256(bytes), onFailure: 'block' };
}

/**
 * `{ ok: true }` only when contract 1 holds in `root`'s working directory for
 * this plugin's entry: no problem and no warning from `checkContract1`, and no
 * problem from `probeContract1` on PROBE_PAYLOAD. Otherwise `{ ok: false,
 * problems }`, warnings counted as problems. The probe starts one process and
 * runs only after the files check out. `probeRoot` is where the probe runs
 * and the entry is built from: the gate passes a private copy of the approved
 * tree, so it never executes the working copy; `checkContract1` always
 * inspects `root`. With `probe` false nothing runs: the answer is
 * checkContract1's alone (status and verify-branch --no-run, which execute
 * nothing from the repository). Never throws: a throw is a problem.
 */
export function contractHolds(root, { probeRoot = root, probe = true } = {}) {
  try {
    const entry = ownEntry(probeRoot);
    const { problems, warnings } = checkContract1(root, entry);
    const found = [...problems, ...warnings];
    if (found.length > 0) return { ok: false, problems: found };
    if (!probe) return { ok: true };
    const probed = probeContract1(probeRoot, entry, { ...PROBE_PAYLOAD, cwd: probeRoot });
    return probed.problems.length > 0 ? { ok: false, problems: probed.problems } : { ok: true };
  } catch (error) {
    return { ok: false, problems: [error instanceof ContractError ? error.message : unexpectedMessage] };
  }
}
